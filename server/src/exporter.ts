// Writes CSV, JSON, SQL, ground truth, validation report and manifests. No timestamps are written,
// so the same seed always produces byte-identical files (and identical checksums).
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { evaluateAgainstGroundTruth } from "./evaluation.js";
import type { Dataset } from "./pipeline.js";
import { TABLE_COLUMNS, TABLE_ORDER } from "./types.js";
import { buildReport, validate } from "./validator.js";

const GT_COLS = ["gt_id", "issue_type", "category", "entity_type", "entity_id", "route_id", "injection_stage", "description", "primary_validation_code", "expected_validation_codes", "expected_decision", "expected_reason_code", "affected_entity_ids"];
export const sha256 = (s: string) => createHash("sha256").update(s).digest("hex");
const csvCell = (v: unknown) => { if (v === null || v === undefined) return ""; const s = String(v); return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s; };
export const toCsv = (rows: any[], cols: string[]) => [cols.join(","), ...rows.map((r) => cols.map((c) => csvCell(r[c])).join(","))].join("\n") + "\n";
export const toJson = (rows: any[]) => "[\n" + rows.map((r) => JSON.stringify(r)).join(",\n") + "\n]\n";
const sqlVal = (v: unknown) => (v === null || v === undefined ? "NULL" : typeof v === "boolean" ? (v ? "TRUE" : "FALSE") : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
export function toSql(table: string, rows: any[], cols: string[]): string {
  const out: string[] = [];
  for (let i = 0; i < rows.length; i += 500) out.push(`INSERT INTO ${table} (${cols.join(", ")}) VALUES\n` + rows.slice(i, i + 500).map((r) => "(" + cols.map((c) => sqlVal(r[c])).join(", ") + ")").join(",\n") + ";");
  return out.join("\n");
}

export function seedSql(ds: Dataset): string {
  return `-- FleetFlow seed data (${ds.variant}, seed ${ds.config.seed}). Synthetic data only.\nBEGIN;\nSET CONSTRAINTS ALL DEFERRED;\n` +
    TABLE_ORDER.map((n) => `-- ${n}: ${ds.tables[n].length} rows\n${toSql(n, ds.tables[n], TABLE_COLUMNS[n])}`).join("\n") + "\nCOMMIT;\n";
}

export function exportDataset(ds: Dataset, dir: string) {
  const findings = validate(ds.tables);
  const report = { variant: ds.variant, seed: ds.config.seed, ...buildReport(ds.tables, findings), ground_truth_evaluation: evaluateAgainstGroundTruth(ds, findings), findings };
  const files = new Map<string, string>();
  for (const n of TABLE_ORDER) { files.set(`csv/${n}.csv`, toCsv(ds.tables[n], TABLE_COLUMNS[n])); files.set(`json/${n}.json`, toJson(ds.tables[n])); }
  files.set("ground_truth/ground_truth.csv", toCsv(ds.ground_truth, GT_COLS));
  files.set("ground_truth/ground_truth.json", toJson(ds.ground_truth));
  files.set("sql/seed.sql", seedSql(ds));
  files.set("validation_report.json", JSON.stringify(report, null, 2) + "\n");
  files.set("validation_report.md", reportMarkdown(report));
  files.set("source_manifest.json", JSON.stringify({
    dataset: `FleetFlow ${ds.variant}`, generator: "server/src/generator.ts", seed: ds.config.seed, scale: ds.config.scale,
    data_origin: "100% synthetic. Generated by code from a fixed random seed.", personal_data: "NONE. Names are random first/last name combinations; coordinates are random points in a synthetic region; registration numbers are fake.",
    external_sources: [], licence_note: "No third-party data used.",
  }, null, 2) + "\n");
  const hashes: Record<string, { sha256: string; bytes: number }> = {};
  for (const [name, text] of files) {
    mkdirSync(dirname(join(dir, name)), { recursive: true });
    writeFileSync(join(dir, name), text);
    hashes[name] = { sha256: sha256(text), bytes: Buffer.byteLength(text) };
  }
  const here = dirname(fileURLToPath(import.meta.url));
  copyFileSync(join(here, "..", "db", "schema.sql"), join(dir, "sql", "schema.sql"));
  const tableHashes = Object.fromEntries(TABLE_ORDER.map((n) => [n, { rows: ds.tables[n].length, csv_sha256: hashes[`csv/${n}.csv`].sha256 }]));
  const manifest = {
    variant: ds.variant, seed: ds.config.seed, scale: ds.config.scale, tables: tableHashes,
    ground_truth: { rows: ds.ground_truth.length, csv_sha256: hashes["ground_truth/ground_truth.csv"].sha256 },
    dataset_checksum: sha256(TABLE_ORDER.map((n) => `${n}:${tableHashes[n].csv_sha256}`).join("\n") + "\nground_truth:" + hashes["ground_truth/ground_truth.csv"].sha256),
    files: hashes,
  };
  writeFileSync(join(dir, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  return { manifest, report, files };
}

function reportMarkdown(r: any): string {
  const ev = r.ground_truth_evaluation;
  const L: string[] = [`# Validation report - ${r.variant} (seed ${r.seed})`, "", "## Record counts", "", "| Table | Rows |", "|---|---:|"];
  for (const [k, v] of Object.entries(r.record_counts)) L.push(`| ${k} | ${v} |`);
  L.push("", "## Summary", "", `- Errors: **${r.summary.errors}**`, `- Warnings: **${r.summary.warnings}**`, `- Checks passed / failed / warning: ${r.summary.checks_passed} / ${r.summary.checks_failed} / ${r.summary.checks_warn} (of ${r.summary.checks_total})`, "", "## Checks", "", "| Code | Severity | Status | Violations | What it checks |", "|---|---|---|---:|---|");
  for (const c of r.checks) L.push(`| ${c.code} | ${c.severity} | ${c.status} | ${c.violations} | ${c.description} |`);
  L.push("", "## Comparison with ground truth (scoring only - the planner never sees ground truth)", "", `- Injected anomalies: ${ev.injected_anomalies}, detected by validator: ${ev.detected}`, `- Error findings NOT explained by any injected anomaly: ${ev.unexplained_error_findings}`, `- Expected planner decisions (unserved + reason): ${ev.expected_decisions_matched} of ${ev.expected_decisions_total} matched`, "");
  return L.join("\n");
}
